"""Legal data of SDE: checks data/legal/components.json and writes the C++
header the About windows and the Control Center read.

  tools/legal-data.py --check
  tools/legal-data.py --header generated/legal_data.h

components.json is the single source of truth for licenses, copyright lines,
upstream credits and trademark notices (docs/LEGAL.md). The header is
regenerated by CMake whenever the JSON file changes."""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'data/legal/components.json'
KINDS = ('desktop', 'application', 'toolkit', 'component', 'theme', 'artwork', 'integration')
RELATIONS = ('fork', 'port', 'adapted', 'build', 'reference')


def load(path=DATA):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def license_parts(expression):
    """'GPL-3.0-or-later AND MIT' -> ['GPL-3.0-or-later', 'MIT']; a WITH
    exception stays part of its license ('LGPL-2.0-only WITH FLTK-exception')."""
    parts = []
    for chunk in expression.replace(' OR ', ' AND ').split(' AND '):
        chunk = chunk.strip().strip('()').strip()
        if chunk:
            parts.append(chunk)
    return parts


def validate(data):
    errors = []
    project = data.get('project', {})
    for key in ('name', 'short_name', 'developer', 'developer_id', 'website', 'copyright', 'license'):
        if not project.get(key):
            errors.append(f'project: missing {key}')
    licenses = data.get('licenses', {})
    for lid, info in licenses.items():
        for key in ('name', 'short_name', 'notice', 'texts', 'url'):
            if key not in info:
                errors.append(f'license {lid}: missing {key}')
    trademarks = data.get('trademarks', {})
    if 'sde' not in trademarks:
        errors.append('trademarks: the SDE notice ("sde") is missing')
    seen = set()
    for c in data.get('components', []):
        cid = c.get('id', '?')
        if cid in seen:
            errors.append(f'{cid}: duplicate id')
        seen.add(cid)
        for key in ('name', 'kind', 'summary', 'license', 'copyright'):
            if not c.get(key):
                errors.append(f'{cid}: missing {key}')
        if c.get('kind') not in KINDS:
            errors.append(f'{cid}: kind must be one of {", ".join(KINDS)}')
        for part in license_parts(c.get('license', '')):
            if part not in licenses:
                errors.append(f'{cid}: license {part} is not described in "licenses"')
        for t in c.get('trademarks', []):
            if t not in trademarks:
                errors.append(f'{cid}: unknown trademark notice {t}')
        for u in c.get('upstream', []):
            for key in ('project', 'url', 'license', 'copyright', 'relation'):
                if not u.get(key):
                    errors.append(f'{cid}: upstream entry without {key}')
            if u.get('relation') not in RELATIONS:
                errors.append(f'{cid}: upstream relation must be one of {", ".join(RELATIONS)}')
            for part in license_parts(u.get('license', '')):
                if part not in licenses:
                    errors.append(f'{cid}: upstream license {part} is not described in "licenses"')
        for line in c.get('copyright', []):
            if not line.startswith('Copyright © '):
                errors.append(f'{cid}: copyright lines start with "Copyright © ": {line}')
        if c.get('kind') == 'application' and not c.get('desktop'):
            errors.append(f'{cid}: applications name their desktop file')
    if 'sde' not in seen:
        errors.append('the desktop itself ("sde") has no entry')
    return errors


def c_string(s):
    out = ['"']
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) < 0x20:
            out.append('\\%03o' % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return ''.join(out)


def write_header(data, path):
    project, licenses, trademarks = data['project'], data['licenses'], data['trademarks']
    out = ['// Generated by tools/legal-data.py from data/legal/components.json. Do not edit.',
           '#pragma once', '', 'namespace sde {', 'namespace legal_data {', '',
           'struct Upstream {',
           '  const char *project, *url, *license, *copyright, *relation;',
           '};',
           'struct License {',
           '  const char *id, *name, *short_name, *notice, *version, *url;',
           '  const char *const *texts;',
           '  int text_count;',
           '};',
           'struct Trademark {',
           '  const char *id, *text;',
           '};',
           'struct Component {',
           '  const char *id, *name, *kind, *summary, *license, *metainfo;',
           '  bool listed;',
           '  const char *const *programs;',
           '  int program_count;',
           '  const char *const *desktop;',
           '  int desktop_count;',
           '  const char *const *icons;',
           '  int icon_count;',
           '  const char *const *copyright;',
           '  int copyright_count;',
           '  const Upstream *upstream;',
           '  int upstream_count;',
           '  const char *const *credits;',
           '  int credit_count;',
           '  const char *const *trademarks;',
           '  int trademark_count;',
           '  const char *const *notices;',
           '  int notice_count;',
           '};', '']
    for key in ('name', 'short_name', 'developer', 'developer_id', 'website', 'bugtracker', 'copyright',
                'license', 'inspiration'):
        const = 'kProject' + ''.join(w.capitalize() for w in key.split('_'))
        out.append(f'inline constexpr const char *{const} = {c_string(project.get(key, ""))};')
    out.append('')

    def array(name, values):
        if not values:
            return 'nullptr', 0
        out.append(f'inline constexpr const char *const {name}[] = {{' +
                   ', '.join(c_string(v) for v in values) + '};')
        return name, len(values)

    lic_rows = []
    for i, (lid, info) in enumerate(licenses.items()):
        texts, n = array(f'kLicenseTexts{i}', info.get('texts', []))
        lic_rows.append(f'    {{{c_string(lid)}, {c_string(info["name"])}, {c_string(info["short_name"])}, '
                        f'{c_string(info["notice"])}, {c_string(info.get("version", ""))}, '
                        f'{c_string(info["url"])}, {texts}, {n}}},')
    out.append('inline constexpr License kLicenses[] = {')
    out.extend(lic_rows)
    out.append('};')
    out.append(f'inline constexpr int kLicenseCount = {len(licenses)};')
    out.append('')
    out.append('inline constexpr Trademark kTrademarks[] = {')
    for tid, text in trademarks.items():
        out.append(f'    {{{c_string(tid)}, {c_string(text)}}},')
    out.append('};')
    out.append(f'inline constexpr int kTrademarkCount = {len(trademarks)};')
    out.append('')

    rows = []
    for i, c in enumerate(data['components']):
        programs = array(f'kPrograms{i}', c.get('programs', []))
        desktop = array(f'kDesktop{i}', c.get('desktop', []))
        icons = array(f'kIcons{i}', c.get('icons', []))
        copyright = array(f'kCopyright{i}', c.get('copyright', []))
        credits = array(f'kCredits{i}', c.get('credits', []))
        marks = array(f'kTrademarkIds{i}', c.get('trademarks', []))
        notices = array(f'kNotices{i}', c.get('notices', []))
        ups = c.get('upstream', [])
        if ups:
            out.append(f'inline constexpr Upstream kUpstream{i}[] = {{')
            for u in ups:
                out.append(f'    {{{c_string(u["project"])}, {c_string(u["url"])}, {c_string(u["license"])}, '
                           f'{c_string(u["copyright"])}, {c_string(u["relation"])}}},')
            out.append('};')
            upstream = (f'kUpstream{i}', len(ups))
        else:
            upstream = ('nullptr', 0)
        rows.append(f'    {{{c_string(c["id"])}, {c_string(c["name"])}, {c_string(c["kind"])}, '
                    f'{c_string(c["summary"])}, {c_string(c["license"])}, {c_string(c.get("metainfo", ""))}, '
                    f'{"true" if c.get("listed", True) else "false"}, '
                    f'{programs[0]}, {programs[1]}, {desktop[0]}, {desktop[1]}, {icons[0]}, {icons[1]}, '
                    f'{copyright[0]}, {copyright[1]}, {upstream[0]}, {upstream[1]}, {credits[0]}, {credits[1]}, '
                    f'{marks[0]}, {marks[1]}, {notices[0]}, {notices[1]}}},')
    out.append('')
    out.append('inline constexpr Component kComponents[] = {')
    out.extend(rows)
    out.append('};')
    out.append(f'inline constexpr int kComponentCount = {len(data["components"])};')
    out.append('')
    out.append('}  // namespace legal_data')
    out.append('}  // namespace sde')
    text = '\n'.join(out) + '\n'
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text(encoding='utf-8') != text:
        path.write_text(text, encoding='utf-8')


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--data', default=str(DATA))
    p.add_argument('--header')
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    data = load(args.data)
    errors = validate(data)
    for e in errors:
        print('legal-data:', e, file=sys.stderr)
    if errors:
        return 1
    if args.header:
        write_header(data, args.header)
    if args.check:
        print(f'{len(data["components"])} components, {len(data["licenses"])} licenses, '
              f'{len(data["trademarks"])} trademark notices')
    return 0


if __name__ == '__main__':
    sys.exit(main())
