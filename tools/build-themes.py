def dedupe(out):
    """Stores identical files once; the others become relative symlinks."""
    seen = {}
    saved = 0
    for path in sorted(p for p in out.rglob('*') if p.is_file() and not p.is_symlink()):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        first = seen.setdefault(digest, path)
        if first is path:
            continue
        saved += path.stat().st_size
        path.unlink()
        path.symlink_to(os.path.relpath(first, path.parent))
    return saved


