def write_header(pal, path):
    acc = pal['accents']
    out = ['// Generated by tools/build-themes.py from data/themes/palettes.json. Do not edit.',
           '#pragma once', '', 'namespace sde {', 'namespace palettes {', '']
    keys = ['background', 'surface', 'surface_alt', 'hover', 'text', 'text_dim', 'border', 'shadow',
            'menu', 'panel', 'titlebar', 'titlebar_inactive', 'titlebar_text',
            'titlebar_text_inactive', 'success', 'warning', 'error']
    out.append('struct Mode {')
    for k in keys:
        out.append(f'  unsigned {k};')
    out.append('  double shadow_alpha;')
    out.append('};')
    out.append('struct Family {')
    out.append('  const char *id, *label, *description, *prefix, *buttons, *title_layout, *menu_highlight;')
    out.append('  int radius, radius_small, radius_large, shadow_radius;')
    out.append('  bool glass;')
    out.append('  double mica, translucency;')
    out.append('  unsigned close_hover;  // caption close button while hovered')
    out.append(f'  unsigned accent[{len(acc)}][2];')
    out.append('  Mode light, dark;')
    out.append('};')
    out.append('struct Legacy { const char *from, *to; };')
    out.append('')
    out.append(f'constexpr int kAccentCount = {len(acc)};')
    out.append('constexpr const char *kAccentIds[] = {' + ', '.join(f'"{a}"' for a in acc) + '};')
    out.append('constexpr const char *kAccentLabels[] = {' +
               ', '.join(f'"{pal["accent_labels"][a]}"' for a in acc) + '};')

    def u(c):
        return '0x' + c.lstrip('#').upper()

    def cstr(s):
        return json.dumps(s, ensure_ascii=False)

    fams = list(pal['families'])
    out.append(f'constexpr int kFamilyCount = {len(fams)};')
    out.append('constexpr Family kFamilies[] = {')
    for fid in fams:
        f = pal['families'][fid]
        accents = family_accents(pal, fid)
        modes = []
        for m in MODES:
            md = f[m]
            modes.append('{' + ', '.join(u(md[k]) for k in keys) + f', {md["shadow_alpha"]}' + '}')
        out.append('  {' + ', '.join([cstr(fid), cstr(f['label']), cstr(f['description']), cstr(f['prefix']),
                                       cstr(f['buttons']), cstr(f['title_layout']),
                                       cstr(f['menu_highlight'])]) + ',')
        out.append(f"   {f['radius']}, {f['radius_small']}, {f['radius_large']}, {f['shadow_radius']}, "
                   f"{'true' if f['glass'] else 'false'}, {f['mica']}, {f['translucency']}, "
                   f"{u(f['caption']['close_hover'])},")
        out.append('   {' + ', '.join('{' + u(accents[a][0]) + ', ' + u(accents[a][1]) + '}' for a in acc) + '},')
        out.append('   ' + ', '.join(modes) + '},')
    out.append('};')
    leg = pal['legacy']
    out.append('constexpr Legacy kLegacyStyles[] = {' +
               ', '.join(f'{{"{k}", "{v}"}}' for k, v in leg['styles'].items()) + '};')
    out.append('constexpr Legacy kLegacyAccents[] = {' +
               ', '.join(f'{{"{k}", "{v}"}}' for k, v in leg['accents'].items()) + '};')
    out.append('constexpr Legacy kLegacyDirectories[] = {' +
               ', '.join(f'{{"{k}", "{v[0]}-{v[1]}"}}' for k, v in leg['directories'].items()) + '};')
    d = pal['default']
    out.append(f'constexpr const char *kDefaultFamily = "{d["family"]}", *kDefaultMode = "{d["mode"]}", '
               f'*kDefaultAccent = "{d["accent"]}";')
    out += ['', '}  // namespace palettes', '}  // namespace sde', '']
    text = '\n'.join(out)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


# ------------------------------------------------------------- Openbox

def xbm(name, rows):
    h, w = len(rows), len(rows[0])
    data = []
    for row in rows:
        for i in range(0, w, 8):
            byte = 0
            for bit, ch in enumerate(row[i:i + 8]):
                if ch == '#':
                    byte |= 1 << bit
            data.append(byte)
    body = ', '.join('0x%02x' % b for b in data)
    return (f'#define {name}_width {w}\n#define {name}_height {h}\n'
            f'static unsigned char {name}_bits[] = {{\n   {body} }};\n')


def grid(size, inside):
    return [''.join('#' if inside(x + 0.5, y + 0.5) else '.' for x in range(size)) for y in range(size)]


def soft_caption_masks():
    """Caption glyphs since 0.1.0~alpha51, after Mint-Y: small, thin glyphs
    (a 6 px minimize dash on the baseline of a 6 px maximize square, two
    overlapping squares for restore) and close as a soft 14 px disc with the
    cross cut out. Hovered or pressed, minimize and maximize get the same disc
    with their glyph cut out, so every state stays round; the theme colors the
    disc (gray, the close button muted red while hovered). The masks are 14 px,
    the size of stock Openbox buttons with a 10 pt title; SDE WM centers them
    in its larger caption buttons, which keep the hit area at the title
    height."""
    n, c, R = 14, 7.0, 6.8

    def disc(x, y):
        return (x - c) ** 2 + (y - c) ** 2 <= R * R

    def cell(lo, hi, v):
        return lo <= int(v) <= hi

    def dash(x, y):
        return cell(4, 9, x) and int(y) == 9

    def square(x, y):
        return cell(4, 9, x) and cell(4, 9, y) and not (cell(5, 8, x) and cell(5, 8, y))

    def restore(x, y):
        front = cell(3, 8, x) and cell(5, 10, y) and not (cell(4, 7, x) and cell(6, 9, y))
        back = (cell(5, 10, x) and int(y) == 3) or (int(x) == 10 and cell(3, 8, y))
        return front or back

    def cross(x, y):
        dx, dy = x - c, y - c
        return max(abs(dx), abs(dy)) <= 2.6 and (abs(dx - dy) < 0.8 or abs(dx + dy) < 0.8)

    def cut(glyph):
        return lambda x, y: disc(x, y) and not glyph(x, y)

    def desk(x, y):
        return (x - c) ** 2 + (y - c) ** 2 <= 6.5

    def shade(x, y):
        return int(y) == 4 and cell(4, 9, x)

    m = {'iconify': grid(n, dash), 'max': grid(n, square), 'max_toggled': grid(n, restore),
         'close': grid(n, cut(cross)), 'desk': grid(n, desk), 'shade': grid(n, shade)}
    for state in ('hover', 'pressed'):
        m[f'iconify_{state}'] = grid(n, cut(dash))
        m[f'max_{state}'] = grid(n, cut(square))
        m[f'max_{state}_toggled'] = grid(n, cut(restore))
        m[f'close_{state}'] = m['close']
    return m


def caption_colors(t, dark, cap, inactive=False):
    """Caption colors shared by SDE WM, GTK and sde::Theme (theme.cpp):
    glyph, disc (close at rest, the others while hovered), pressed disc,
    close while hovered and pressed."""
    bar = t['titlebar_inactive'] if inactive else t['titlebar']
    if inactive:
        glyph = t['titlebar_text_inactive']
        disc = mix(bar, t['titlebar_text'], 0.26 if not dark else 0.30)
    else:
        glyph = mix(t['titlebar_text'], bar, 0.15)
        disc = mix(bar, t['titlebar_text'], 0.40 if not dark else 0.38)
    press = mix(bar, t['titlebar_text'], 0.58)
    close = cap['close_hover']
    return {'glyph': glyph, 'disc': disc, 'press': press, 'close': close,
            'close_press': mix(close, '#000000', 0.15)}


def caption_masks(glyph='thin'):
    """Caption glyphs of every family: minimize (a bar), maximize (a square),
    restore (two squares, shown while maximized) and close (a cross). The
    "thin" glyphs are 10 px with 1 px strokes (Fluent, after Segoe Fluent
    Icons); "regular" ones are 11 px with a heavier cross (Graphite, Glass);
    "soft" ones (0.1.0~alpha51, every family) come from soft_caption_masks()."""
    if glyph == 'soft':
        return soft_caption_masks()
    n = 10 if glyph == 'thin' else 11
    w = 0.75 if glyph == 'thin' else 1.05  # half the width of the cross strokes

    def close(x, y):
        return abs(x - y) < w or abs(x + y - n) < w

    def iconify(x, y):
        mid = n / 2
        return mid - 0.4 <= y < mid + 0.6

    def maxi(x, y):
        return (0.5 <= x < n - 0.5 and 0.5 <= y < n - 0.5) and not (1.5 <= x < n - 1.5 and 1.5 <= y < n - 1.5)

    def restore(x, y):
        f = n - 2.5  # the front square
        front = (0.5 <= x < f and 2.5 <= y < n - 0.5) and not (1.5 <= x < f - 1 and 3.5 <= y < n - 1.5)
        back = ((2.5 <= x < n - 0.5 and 0.5 <= y < 1.5) or (n - 1.5 <= x < n - 0.5 and 0.5 <= y < f))
        return front or back

    def desk(x, y):
        c = n / 2
        return (x - c) ** 2 + (y - c) ** 2 <= n * 0.65

    def shade(x, y):
        return 1.5 <= y < 2.5 and 0.5 <= x < n - 0.5

    return {'close': grid(n, close), 'iconify': grid(n, iconify), 'max': grid(n, maxi),
            'max_toggled': grid(n, restore), 'desk': grid(n, desk), 'shade': grid(n, shade)}


def bullet_mask(fluent):
    n = 8 if fluent else 7

    def chevron(x, y):
        return abs((x - 2.2) - abs(y - n / 2)) < 0.9 and 1 <= y < n - 1

    return grid(n, chevron)


def openbox_theme(pal, family, mode, accent, outdir):
    fam = pal['families'][family]
    t = tokens(pal, family, mode, accent)
    fluent = family == 'fluent'
    cap = fam['caption']
    dark = mode == 'dark'
    ob = Path(outdir) / 'openbox-3'
    ob.mkdir(parents=True, exist_ok=True)
    masks = caption_masks(cap['glyph'])
    for name, rows in masks.items():
        (ob / f'{name}.xbm').write_text(xbm(name, rows))
    (ob / 'bullet.xbm').write_text(xbm('bullet', bullet_mask(fluent)))
    sel_bg = t['accent'] if fam['menu_highlight'] == 'accent' else t['hover']
    sel_fg = t['on_accent'] if fam['menu_highlight'] == 'accent' else t['text']
    # Same rule as sde::Theme: deepen bright accents until labels are readable.
    i = 1
    while fam['menu_highlight'] == 'accent' and contrast(sel_fg, sel_bg) < 4.5 and i <= 10:
        sel_bg = mix(t['accent'], '#000000' if luminance(sel_fg) > 0.5 else '#FFFFFF', i * 0.04)
        i += 1
    # A quiet frame line: the compositor's soft shadow and rounded corners
    # do the separating (alpha51; Fluent no longer tints it with the accent).
    border_active = mix(t['border'], t['titlebar_text'], 0.08) if cap['glyph'] == 'soft' else (
        mix(t['border'], t['accent'], 0.25) if fluent else t['border'])
    L = [f'# {theme_name(pal, family, mode, accent)}: window frames for SDE WM (Openbox).',
         '# Generated by tools/build-themes.py from data/themes/palettes.json.',
         f'# Part of SDE {fam["label"]}; GTK parts from {fam["upstream"]} (see /usr/share/doc/sde/themes).',
         '', 'border.width: 1',
         'padding.width: 8', 'padding.height: 8',
         'window.handle.width: 0', 'window.client.padding.width: 0', 'window.client.padding.height: 0',
         'menu.overlap.x: -2', 'menu.overlap.y: 0',
         # SDE WM extension (suite/patches/sde-wm): wide caption buttons sized
         # from the title height, so they follow the font and the UI scale.
         # Stock Openbox ignores these keys and keeps its small buttons.
         f'window.button.width.percent: {cap["width"]}',
         f'window.button.height.percent: {cap["height"]}',
         f'window.button.spacing: {cap["spacing"]}', '',
         f'window.active.border.color: {border_active}',
         f'window.inactive.border.color: {t["border"]}',
         f'window.active.title.separator.color: {t["titlebar"]}',
         f'window.inactive.title.separator.color: {t["titlebar_inactive"]}',
         f'window.active.client.color: {t["background"]}',
         f'window.inactive.client.color: {t["background"]}', '']
    if fam['glass'] and cap['glyph'] != 'soft':
        # Glass: a soft vertical sheen; the compositor adds blur and translucency.
        top = mix(t['titlebar'], '#FFFFFF', 0.10 if dark else 0.55)
        L += ['window.active.title.bg: flat gradient vertical',
              f'window.active.title.bg.color: {top}',
              f'window.active.title.bg.colorTo: {t["titlebar"]}',
              'window.inactive.title.bg: flat solid',
              f'window.inactive.title.bg.color: {t["titlebar_inactive"]}']
    else:
        # Since alpha51 every family has a flat title bar (Glass gets its
        # frosted look from the compositor's blur, not from a gradient).
        L += ['window.active.title.bg: flat solid', f'window.active.title.bg.color: {t["titlebar"]}',
              'window.inactive.title.bg: flat solid',
              f'window.inactive.title.bg.color: {t["titlebar_inactive"]}']
    L += ['window.active.label.bg: parentrelative', 'window.inactive.label.bg: parentrelative',
          f'window.active.label.text.color: {t["titlebar_text"]}',
          f'window.inactive.label.text.color: {t["titlebar_text_inactive"]}',
          f'window.label.text.justify: {fam["title_justify"]}', '']
    if cap['glyph'] == 'soft':
        # Mint-Y like caption buttons (0.1.0~alpha51): the button background
        # stays the title bar; the masks draw the round shapes (see
        # soft_caption_masks()), so only image colors change with the state.
        for state in ('active', 'inactive'):
            k = caption_colors(t, dark, cap, inactive=state == 'inactive')
            L += [f'window.{state}.button.unpressed.bg: parentrelative',
                  f'window.{state}.button.unpressed.image.color: {k["glyph"]}',
                  f'window.{state}.button.hover.bg: parentrelative',
                  f'window.{state}.button.hover.image.color: {k["disc"]}',
                  f'window.{state}.button.pressed.bg: parentrelative',
                  f'window.{state}.button.pressed.image.color: {k["press"]}',
                  f'window.{state}.button.disabled.bg: parentrelative',
                  f'window.{state}.button.disabled.image.color: {mix(k["glyph"], t["titlebar"], 0.6)}',
                  f'window.{state}.button.toggled.bg: parentrelative',
                  f'window.{state}.button.toggled.image.color: {k["glyph"]}',
                  f'window.{state}.button.toggled.hover.bg: parentrelative',
                  f'window.{state}.button.toggled.hover.image.color: {k["disc"]}',
                  f'window.{state}.button.toggled.pressed.bg: parentrelative',
                  f'window.{state}.button.toggled.pressed.image.color: {k["press"]}',
                  f'window.{state}.button.close.unpressed.bg: parentrelative',
                  f'window.{state}.button.close.unpressed.image.color: {k["disc"]}',
                  f'window.{state}.button.close.hover.bg: parentrelative',
                  f'window.{state}.button.close.hover.image.color: {k["close"]}',
                  f'window.{state}.button.close.pressed.bg: parentrelative',
                  f'window.{state}.button.close.pressed.image.color: {k["close_press"]}', '']
        return finish_openbox(L, t, fam, sel_bg, sel_fg, ob)
    inactive_glyph = t['titlebar_text_inactive']
    # Caption buttons: clear glyphs, a hover layer over the title bar and a
    # red close, the same in every family and in GTK header bars.
    hover = mix(t['titlebar'], t['titlebar_text'], 0.10 if not dark else 0.12)
    press = mix(t['titlebar'], t['titlebar_text'], 0.18 if not dark else 0.22)
    close_bg = cap['close_hover']
    close_press = mix(close_bg, '#000000', 0.12)
    for state in ('active', 'inactive'):
        glyph = t['titlebar_text'] if state == 'active' else inactive_glyph
        L += [f'window.{state}.button.unpressed.bg: parentrelative',
              f'window.{state}.button.unpressed.image.color: {glyph}',
              f'window.{state}.button.hover.bg: flat solid',
              f'window.{state}.button.hover.bg.color: {hover}',
              f'window.{state}.button.hover.image.color: {t["titlebar_text"]}',
              f'window.{state}.button.pressed.bg: flat solid',
              f'window.{state}.button.pressed.bg.color: {press}',
              f'window.{state}.button.pressed.image.color: {t["titlebar_text"]}',
              f'window.{state}.button.disabled.bg: parentrelative',
              f'window.{state}.button.disabled.image.color: {mix(glyph, t["titlebar"], 0.6)}',
              f'window.{state}.button.toggled.bg: parentrelative',
              f'window.{state}.button.toggled.image.color: {glyph}',
              f'window.{state}.button.toggled.hover.bg: flat solid',
              f'window.{state}.button.toggled.hover.bg.color: {hover}',
              f'window.{state}.button.toggled.hover.image.color: {t["titlebar_text"]}',
              f'window.{state}.button.toggled.pressed.bg: flat solid',
              f'window.{state}.button.toggled.pressed.bg.color: {press}',
              f'window.{state}.button.toggled.pressed.image.color: {t["titlebar_text"]}',
              f'window.{state}.button.close.hover.bg: flat solid',
              f'window.{state}.button.close.hover.bg.color: {close_bg}',
              f'window.{state}.button.close.hover.image.color: #FFFFFF',
              f'window.{state}.button.close.pressed.bg: flat solid',
              f'window.{state}.button.close.pressed.bg.color: {close_press}',
              f'window.{state}.button.close.pressed.image.color: #FFFFFF', '']
    finish_openbox(L, t, fam, sel_bg, sel_fg, ob)


def finish_openbox(L, t, fam, sel_bg, sel_fg, ob):
    """Handles, menus and OSD of an Openbox theme; writes themerc."""
    for part in ('handle', 'grip'):
        L += [f'window.active.{part}.bg: flat solid', f'window.active.{part}.bg.color: {t["titlebar"]}',
              f'window.inactive.{part}.bg: flat solid',
              f'window.inactive.{part}.bg.color: {t["titlebar_inactive"]}']
    menu_border = t['border']
    L += ['', 'menu.border.width: 1', f'menu.border.color: {menu_border}',
          'menu.items.bg: flat solid', f'menu.items.bg.color: {t["menu"]}',
          f'menu.items.text.color: {t["text"]}',
          f'menu.items.disabled.text.color: {mix(t["text_dim"], t["menu"], 0.35)}',
          'menu.items.active.bg: flat solid', f'menu.items.active.bg.color: {sel_bg}',
          f'menu.items.active.text.color: {sel_fg}',
          f'menu.items.active.disabled.text.color: {mix(sel_fg, sel_bg, 0.5)}',
          'menu.title.bg: flat solid', f'menu.title.bg.color: {t["menu"]}',
          f'menu.title.text.color: {t["text_dim"]}', 'menu.title.text.justify: left',
          f'menu.separator.color: {t["border"]}', 'menu.separator.width: 1',
          'menu.separator.padding.width: 10', 'menu.separator.padding.height: 4',
          f'menu.bullet.image.color: {t["text_dim"]}',
          f'menu.bullet.selected.image.color: {sel_fg}', '',
          'osd.border.width: 1', f'osd.border.color: {t["border"]}',
          'osd.bg: flat solid', f'osd.bg.color: {t["menu"]}',
          'osd.label.bg: parentrelative', f'osd.label.text.color: {t["text"]}',
          'osd.hilight.bg: flat solid', f'osd.hilight.bg.color: {t["accent"]}',
          'osd.unhilight.bg: flat solid', f'osd.unhilight.bg.color: {t["border"]}',
          'osd.button.unpressed.bg: flat solid', f'osd.button.unpressed.bg.color: {t["surface_alt"]}',
          f'osd.button.unpressed.text.color: {t["text"]}',
          'osd.button.pressed.bg: flat solid', f'osd.button.pressed.bg.color: {t["accent"]}',
          f'osd.button.pressed.text.color: {t["on_accent"]}',
          'osd.button.focused.bg: flat solid', f'osd.button.focused.bg.color: {t["hover"]}',
          f'osd.button.focused.text.color: {t["text"]}',
          f'osd.button.focused.box.color: {t["accent"]}', '']
    (ob / 'themerc').write_text('\n'.join(L))


