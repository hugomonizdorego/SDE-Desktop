"""Build the SDE themes (GTK 3, GTK 4, libadwaita colors and Openbox) for
/usr/share/themes from data/themes/palettes.json and the upstream sources
prepared by tools/prepare-themes.py.

  SDE-Graphite-{Light,Dark}-<Accent>  from vinceliuice/Graphite-gtk-theme,
                                      compiled with sassc (the default theme)
  SDE-Fluent-{Light,Dark}-<Accent>    from daniruiz/flat-remix-gtk, with the
                                      Flat Remix GNOME Shell palette
  SDE-Glass-{Light,Dark}-<Accent>     SDE's glass layer on SDE Graphite
  SDE, SDE-Dark, SDE-Aero, ...        aliases for the alpha15 theme names

Every theme has an openbox-3 window theme drawn from the same palette, so
title bars, buttons and the root menu match the applications.

  tools/build-themes.py --output DIR [--vendor vendor/themes]
  tools/build-themes.py --header generated/theme_palettes.h
  tools/build-themes.py --openbox-only --output DIR   (no upstream sources)

Identical files are stored once and linked, which keeps the 54 themes small."""
