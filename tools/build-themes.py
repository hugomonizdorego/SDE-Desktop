# ------------------------------------------------------------------ colors

def rgb(hexstr):
    h = hexstr.lstrip('#')
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def hexc(c):
    return '#%02X%02X%02X' % tuple(max(0, min(255, round(v * 255))) for v in c)


def mix(a, b, t):
    ca, cb = rgb(a), rgb(b)
    return hexc(tuple(x + (y - x) * t for x, y in zip(ca, cb)))


def luminance(c):
    def lin(v):
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = rgb(c)
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def on_color(c):
    return '#17191E' if contrast(c, '#17191E') > contrast(c, '#FFFFFF') else '#FFFFFF'


def rgba(c, a):
    r, g, b = (round(v * 255) for v in rgb(c))
    return f'rgba({r}, {g}, {b}, {a:.2f})'


def family_accents(pal, family):
    acc = pal['families'][family]['accent']
    if isinstance(acc, str):
        acc = pal['families'][acc]['accent']
    return acc


def accent_for(pal, family, mode, accent):
    return family_accents(pal, family)[accent][0 if mode == 'light' else 1]


def tokens(pal, family, mode, accent):
    """The resolved palette of one theme, as used by SDE and Openbox."""
    fam = pal['families'][family]
    t = dict(fam[mode])
    t['accent'] = accent_for(pal, family, mode, accent)
    t['on_accent'] = on_color(t['accent'])
    if fam['mica']:
        # Mica: the window background picks up a little of the accent.
        t['background'] = mix(t['background'], t['accent'], fam['mica'])
        t['titlebar'] = mix(t['titlebar'], t['accent'], fam['mica'] * 1.4)
        t['titlebar_inactive'] = mix(t['titlebar_inactive'], t['accent'], fam['mica'] * 0.6)
    return t


def theme_name(pal, family, mode, accent):
    label = pal['accent_labels'][accent]
    return f"{pal['families'][family]['prefix']}-{mode.capitalize()}-{label}"


