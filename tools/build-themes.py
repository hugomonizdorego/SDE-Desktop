def build_aliases(pal, out):
    """Theme names of alpha15 and earlier keep working (blue accent)."""
    for old, (family, mode) in pal['legacy']['directories'].items():
        target = theme_name(pal, family, mode, pal['default']['accent'])
        d = out / old
        for gtk in ('gtk-3.0', 'gtk-4.0'):
            write(d / gtk / 'gtk.css', f'/* {old} is now {target}. */\n@import url("../../{target}/{gtk}/gtk.css");\n')
            write(d / gtk / 'gtk-dark.css', f'@import url("../../{target}/{gtk}/gtk-dark.css");\n')
        write(d / 'index.theme', index_theme(old, old, f'Former SDE theme name; now {target}', mode == 'dark'))
        openbox_theme(pal, family, mode, pal['default']['accent'], d)


def dedupe(out):
    """Stores identical files once; the others become relative symlinks."""
    seen = {}
    saved = 0
    for path in sorted(p for p in out.rglob('*') if p.is_file() and not p.is_symlink()):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        first = seen.setdefault(digest, path)
        if first is path:
            continue
        saved += path.stat().st_size
        path.unlink()
        path.symlink_to(os.path.relpath(first, path.parent))
    return saved


def copy_docs(vendor, out):
    lock = json.loads((ROOT / 'suite/themes.lock.json').read_text())
    for entry in lock['themes']:
        src = vendor / entry['id']
        d = out / entry['id']
        d.mkdir(parents=True, exist_ok=True)
        for name in ('LICENSE', 'README.md', 'AUTHORS', 'SDE-SOURCE'):
            if (src / name).is_file():
                shutil.copy2(src / name, d / name)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--output', type=Path)
    p.add_argument('--vendor', type=Path, default=ROOT / 'vendor/themes')
    p.add_argument('--docs', type=Path, help='copy upstream licenses and READMEs here')
    p.add_argument('--header', type=Path, help='write the C++ palette header and exit')
    p.add_argument('--openbox-only', action='store_true',
                   help='only the Openbox themes (when the upstream sources are not prepared)')
    args = p.parse_args()
    pal = load_palettes()
    if args.header:
        write_header(pal, args.header)
        if not args.output:
            return
    if not args.output:
        p.error('--output is required')
    out = args.output
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    if args.openbox_only:
        for family in pal['families']:
            for mode in MODES:
                for accent in pal['accents']:
                    openbox_theme(pal, family, mode, accent, out / theme_name(pal, family, mode, accent))
        for old, (family, mode) in pal['legacy']['directories'].items():
            openbox_theme(pal, family, mode, pal['default']['accent'], out / old)
    else:
        for need in ('graphite-gtk-theme', 'flat-remix-gtk'):
            if not (args.vendor / need).is_dir():
                sys.exit(f'build-themes: {args.vendor / need} is missing; run tools/prepare-themes.py')
        with tempfile.TemporaryDirectory(prefix='sde-themes-') as work:
            build_graphite(pal, args.vendor, out, work)
        build_fluent(pal, args.vendor, out)
        build_glass(pal, out)
        build_aliases(pal, out)
        if args.docs:
            copy_docs(args.vendor, args.docs)
    saved = dedupe(out)
    total = sum(p.stat().st_size for p in out.rglob('*') if p.is_file() and not p.is_symlink())
    print(f'build-themes: {len([d for d in out.iterdir() if d.is_dir()])} themes, '
          f'{total / 1e6:.1f} MB ({saved / 1e6:.1f} MB shared)')


if __name__ == '__main__':
    main()
